"use strict";

(function () {
  /* eslint-disable max-len */
  /* eslint-disable no-use-before-define */
  /* eslint-disable no-console */
  (function pcat72Iframe() {
    const pcat72Config = {
      loanTerms: [2, 3, 4, 5],
      frequencies: [{
        label: 'Weekly',
        duration: 0
      }, {
        label: 'Fortnightly',
        duration: 1
      }, {
        label: 'Monthly',
        duration: 2
      }],
      urls: {
        retailer: 'https://findadealer.peugeot.com.au/',
        enquiry: 'https://www.peugeot.com.au/tools/enquiry.html'
      },
      termsHtml: '<p>*This is an indicative finance calculator, provided by PEUGEOT Australia, to provide with you with a rough idea of what your personal vehicle finance repayments might be based on financial variables inputted by you. This calculator is provided by PEUGEOT Australia to allow potential finance applicants to calculate an approximation of the potential repayments payable depending on different financial variables. It is not a quotation or offer of finance, or any representation that any offer of finance will be made, or application for finance will be accepted, based on the financial variables of the calculator. The values generated by this calculator should not be relied upon in making a decision in relation to any finance product, and all potential applicants should speak to their financial adviser before making any decision in relation to finance.</p>',
      heightBuffer: 40,
      heightSyncInterval: 1000
    };
    let pcat72CollapsedHeight = null;
    let pcat72IsLoading = true;
    function pcat72HasUrlParam() {
      const params = new URLSearchParams(window.location.search);
      return params.get('pcat72') === 'testing';
    }
    function pcat72ShowLoadingOverlay() {
      document.documentElement.classList.add('pcat72-is-loading');
    }
    function pcat72HideLoadingOverlay() {
      document.documentElement.classList.remove('pcat72-is-loading');
    }
    function pcat72BindVariantChangeOverlay() {
      const modelVariant = document.getElementById('model-variant');
      if (!modelVariant || modelVariant.dataset.pcat72OverlayBound === 'true') {
        return;
      }
      modelVariant.dataset.pcat72OverlayBound = 'true';
      Kameleoon.API.Utils.addEventListener(modelVariant, 'change', () => {
        pcat72ShowLoadingOverlay();
      }, true);
    }
    function pcat72FormatPercent(value) {
      const num = parseFloat(value, 10);
      if (Number.isNaN(num)) {
        return '0.1%';
      }
      if (Number.isInteger(num)) {
        return `${num}%`;
      }
      return `${num.toFixed(1)}%`;
    }
    function pcat72FormatDeposit(value) {
      const num = Number(value);
      if (Number.isNaN(num)) {
        return '$0';
      }
      return `$${num.toLocaleString('en-AU', {
        maximumFractionDigits: 0
      })}`;
    }
    function pcat72FormatMoneyLabel(value) {
      const num = Number(value);
      if (Number.isNaN(num)) {
        return '$0.00';
      }
      return `$${num.toLocaleString('en-AU', {
        minimumFractionDigits: 2,
        maximumFractionDigits: 2
      })}`;
    }
    function pcat72GetVehicleValue() {
      const vehicleInput = document.getElementById('vehicleValue');
      if (!vehicleInput) {
        return '';
      }
      return vehicleInput.value;
    }
    function pcat72GetMaxDeposit() {
      const cashInput = document.getElementById('cash');
      if (cashInput && cashInput.max) {
        return Number(cashInput.max);
      }
      const vehicleValue = pcat72GetVehicleValue();
      return Number(vehicleValue.replace(/[^0-9.-]+/g, '')) || 0;
    }
    function pcat72TriggerCalculation() {
      const interestInput = document.getElementById('interest');
      const loanInput = document.getElementById('loan');
      const cashInput = document.getElementById('cash');
      const vehicleValue = pcat72GetVehicleValue();
      if (!interestInput || !loanInput || !cashInput || !vehicleValue || typeof window.calculateLoan !== 'function') {
        return;
      }
      window.calculateLoan(vehicleValue, interestInput.value, loanInput.value, cashInput.value);
    }
    function pcat72UpdateInterestDisplay(value) {
      const display = document.getElementById('pcat72-interest-display');
      if (display) {
        display.textContent = pcat72FormatPercent(value).replace('%', '');
      }
    }
    function pcat72UpdateDepositDisplay(value) {
      const display = document.getElementById('pcat72-deposit-display');
      if (display) {
        display.textContent = pcat72FormatDeposit(value);
      }
      const maxLabel = document.getElementById('pcat72-deposit-max');
      if (maxLabel) {
        maxLabel.textContent = pcat72FormatMoneyLabel(pcat72GetMaxDeposit());
      }
    }
    function pcat72UpdateLoanTermButtons(activeYears) {
      document.querySelectorAll('.pcat72-loan-term__btn').forEach(button => {
        button.classList.toggle('is-active', Number(button.dataset.years) === Number(activeYears));
      });
    }
    function pcat72BuildLoanTermHtml() {
      return `
            <div class="pcat72-loan-term">
                <p class="pcat72-field-label">Select a loan term</p>
                <div class="pcat72-loan-term__options" role="group" aria-label="Select a loan term">
                    ${pcat72Config.loanTerms.map(years => `
                        <button
                            type="button"
                            class="pcat72-loan-term__btn${years === 2 ? ' is-active' : ''}"
                            data-years="${years}">
                            ${years} years
                        </button>
                    `).join('')}
                </div>
            </div>
        `;
    }
    function pcat72BuildCtasHtml() {
      return `
            <div class="pcat72-cta-group">
                <a class="pcat72-cta pcat72-cta--outline" href="${pcat72Config.urls.retailer}" target="_blank" rel="noopener noreferrer" data-pcat72-cta="t72_contact_a_retailer">
                    Contact a Retailer
                </a>
                <a class="pcat72-cta pcat72-cta--primary" href="${pcat72Config.urls.enquiry}" target="_blank" rel="noopener noreferrer" data-pcat72-cta="t72_make_a_finance_enquiry">
                    Make a Finance Enquiry
                </a>
            </div>
        `;
    }
    function pcat72BuildTermsHtml() {
      return `
            <div class="pcat72-terms">
                <button type="button" class="pcat72-terms__toggle" aria-expanded="false">
                    <span>Terms &amp; Conditions</span>
                    <span class="pcat72-terms__icon" aria-hidden="true"></span>
                </button>
                <div class="pcat72-terms__content" hidden>
                    ${pcat72Config.termsHtml}
                </div>
            </div>
        `;
    }
    function pcat72TransformCalculatorUi() {
      const calculatorForm = document.querySelector('.calculator-form');
      if (!calculatorForm || calculatorForm.classList.contains('pcat72-ready')) {
        return;
      }
      calculatorForm.classList.add('pcat72-ready');
      const interestSection = calculatorForm.querySelector('.interest-rate');
      const loanSection = calculatorForm.querySelector('.loan-term');
      const depositSection = calculatorForm.querySelector('.cash-deposit');
      const frequencySection = calculatorForm.querySelector('.calculator-time');
      const repaymentSection = calculatorForm.querySelector('.weekly-repayment');
      if (interestSection) {
        const interestLabel = interestSection.querySelector('p');
        if (interestLabel) {
          interestLabel.innerHTML = 'Select your interest rate: <span class="pcat72-value"><span id="pcat72-interest-display">0.1</span>%</span>';
        }
      }
      if (loanSection) {
        loanSection.classList.add('pcat72-loan-term-section');
        const nativeLoanLabel = loanSection.querySelector('p');
        const nativeLoanSlider = loanSection.querySelector('.calculator-slider-contain');
        if (nativeLoanLabel) {
          nativeLoanLabel.classList.add('pcat72-native-hidden');
        }
        if (nativeLoanSlider) {
          nativeLoanSlider.classList.add('pcat72-native-hidden');
        }
        loanSection.insertAdjacentHTML('beforeend', pcat72BuildLoanTermHtml());
      }
      if (depositSection) {
        const depositLabel = depositSection.querySelector('p');
        const depositSpans = depositSection.querySelectorAll('.calculator-slider-contain > span');
        if (depositLabel) {
          depositLabel.innerHTML = 'Choose a deposit amount: <span class="pcat72-value" id="pcat72-deposit-display">$0</span>';
        }
        if (depositSpans[0]) {
          depositSpans[0].textContent = '$0';
        }
        if (depositSpans[2]) {
          depositSpans[2].id = 'pcat72-deposit-max';
          depositSpans[2].textContent = pcat72FormatMoneyLabel(pcat72GetMaxDeposit());
        }
      }
      if (frequencySection) {
        frequencySection.classList.add('pcat72-frequency');
      }
      if (repaymentSection) {
        repaymentSection.classList.add('pcat72-repayment');
        const breakEl = repaymentSection.querySelector('br');
        if (breakEl) {
          breakEl.remove();
        }
      }
      calculatorForm.insertAdjacentHTML('beforeend', `${pcat72BuildCtasHtml()}${pcat72BuildTermsHtml()}`);
    }
    function pcat72SetNativeDefaults() {
      const interestInput = document.getElementById('interest');
      const loanInput = document.getElementById('loan');
      const cashInput = document.getElementById('cash');
      if (interestInput) {
        interestInput.value = '0.1';
        const outputInterest = document.getElementById('value-interest');
        if (outputInterest) {
          outputInterest.textContent = '0.1';
        }
        pcat72UpdateInterestDisplay('0.1');
      }
      if (loanInput) {
        loanInput.value = '2';
        const outputLoan = document.getElementById('value-loan');
        if (outputLoan) {
          outputLoan.textContent = '2';
        }
        pcat72UpdateLoanTermButtons(2);
      }
      if (cashInput) {
        cashInput.value = '0';
        const outputCash = document.getElementById('value-cash');
        if (outputCash) {
          outputCash.textContent = '0';
        }
        pcat72UpdateDepositDisplay(0);
      }
      const weeklyTab = document.querySelector('.calculator-time .time-selection[data-duration="0"]');
      if (weeklyTab && !weeklyTab.classList.contains('active-time')) {
        document.querySelectorAll('.calculator-time .time-selection').forEach(tab => {
          tab.classList.remove('active-time');
        });
        weeklyTab.classList.add('active-time');
      }
    }
    function pcat72UpdateSliderFill(slider) {
      const min = Number(slider.min) || 0;
      const max = Number(slider.max) || 100;
      const percent = (Number(slider.value) - min) / (max - min) * 100;
      slider.style.setProperty('--pcat72-slider-fill', `${percent}%`);
    }
    function pcat72InitSliderFills() {
      document.querySelectorAll('.calculator-slider-inner').forEach(slider => {
        pcat72UpdateSliderFill(slider);
        Kameleoon.API.Utils.addEventListener(slider, 'input', () => {
          pcat72UpdateSliderFill(slider);
        });
      });
    }
    function pcat72BindEvents() {
      const interestInput = document.getElementById('interest');
      const cashInput = document.getElementById('cash');
      if (interestInput) {
        Kameleoon.API.Utils.addEventListener(interestInput, 'input', () => {
          pcat72UpdateInterestDisplay(interestInput.value);
        });
        Kameleoon.API.Utils.addEventListener(interestInput, 'change', pcat72TriggerCalculation);
      }
      if (cashInput) {
        Kameleoon.API.Utils.addEventListener(cashInput, 'input', () => {
          pcat72UpdateDepositDisplay(cashInput.value);
        });
        Kameleoon.API.Utils.addEventListener(cashInput, 'change', pcat72TriggerCalculation);
      }
      document.querySelectorAll('.pcat72-loan-term__btn').forEach(button => {
        Kameleoon.API.Utils.addEventListener(button, 'click', () => {
          const loanInput = document.getElementById('loan');
          const {
            years
          } = button.dataset;
          if (!loanInput || !years) {
            return;
          }
          loanInput.value = years;
          const outputLoan = document.getElementById('value-loan');
          if (outputLoan) {
            outputLoan.textContent = years;
          }
          pcat72UpdateLoanTermButtons(years);
          pcat72TriggerCalculation();
        });
      });
      document.querySelectorAll('.calculator-time .time-selection').forEach(tab => {
        Kameleoon.API.Utils.addEventListener(tab, 'click', () => {
          window.setTimeout(pcat72TriggerCalculation, 0);
        });
      });
      const termsToggle = document.querySelector('.pcat72-terms__toggle');
      const termsContent = document.querySelector('.pcat72-terms__content');
      if (termsToggle && termsContent) {
        const termsSection = termsToggle.closest('.pcat72-terms');
        Kameleoon.API.Utils.addEventListener(termsToggle, 'click', () => {
          const isOpen = termsToggle.getAttribute('aria-expanded') === 'true';
          const willOpen = !isOpen;
          termsToggle.setAttribute('aria-expanded', willOpen ? 'true' : 'false');
          termsToggle.classList.toggle('is-open', willOpen);
          termsContent.hidden = !willOpen;
          if (termsSection) {
            termsSection.classList.toggle('is-open', willOpen);
          }
          document.body.classList.toggle('pcat72-terms-expanded', willOpen);
          window.requestAnimationFrame(() => {
            window.requestAnimationFrame(pcat72SendHeightToParent);
          });
        });
      }
      const postcodeLink = document.querySelector('.calculator-inner .calc-text a');
      if (postcodeLink) {
        Kameleoon.API.Utils.addEventListener(postcodeLink, 'click', pcat72NotifyParentScrollToIframe);
      }
      document.querySelectorAll('[data-pcat72-cta]').forEach(cta => {
        Kameleoon.API.Utils.addEventListener(cta, 'click', () => {
          pcat72NotifyParentCtaClick(cta.dataset.pcat72Cta);
        });
      });
      pcat72BindVariantChangeOverlay();
    }
    function pcat72NotifyParentCtaClick(ctaName) {
      try {
        if (window.parent === window.self || !ctaName) {
          return;
        }
        window.parent.postMessage({
          type: 'PCAT72_CTA_CLICK',
          cta: ctaName
        }, '*');
      } catch (error) {
        // ignore cross-origin access errors
      }
    }
    function pcat72NotifyParentScrollToIframe() {
      try {
        if (window.parent === window.self) {
          return;
        }
        window.parent.postMessage({
          type: 'PCAT72_SCROLL_TO_IFRAME'
        }, '*');
      } catch (error) {
        // ignore cross-origin access errors
      }
    }
    function pcat72GetCollapsedContentHeight() {
      const contentEl = document.querySelector('.calculator-inner') || document.querySelector('.calculator') || document.querySelector('#main') || document.body;
      const docTop = document.documentElement.getBoundingClientRect().top;
      const contentRect = contentEl.getBoundingClientRect();
      return Math.max(Math.ceil(contentRect.bottom - docTop), Math.ceil(contentEl.offsetTop + contentEl.offsetHeight));
    }
    function pcat72GetTermsOverflowHeight() {
      const termsContent = document.querySelector('.pcat72-terms__content');
      const termsToggle = document.querySelector('.pcat72-terms__toggle');
      if (!termsContent || termsContent.hidden || termsToggle?.getAttribute('aria-expanded') !== 'true') {
        return 0;
      }
      return Math.ceil(termsContent.getBoundingClientRect().height);
    }
    function pcat72SendHeightToParent() {
      if (pcat72IsLoading) {
        return;
      }
      try {
        if (window.parent === window.self) {
          return;
        }
        const termsToggle = document.querySelector('.pcat72-terms__toggle');
        const termsExpanded = termsToggle?.getAttribute('aria-expanded') === 'true';
        const collapsedContentHeight = pcat72GetCollapsedContentHeight();
        const termsOverflow = pcat72GetTermsOverflowHeight();
        if (!termsExpanded) {
          pcat72CollapsedHeight = collapsedContentHeight + pcat72Config.heightBuffer;
        }
        const collapsedHeight = pcat72CollapsedHeight || collapsedContentHeight + pcat72Config.heightBuffer;
        const heightWithBuffer = termsExpanded ? collapsedHeight + termsOverflow : collapsedContentHeight + pcat72Config.heightBuffer;
        if (termsExpanded) {
          document.body.style.height = `${heightWithBuffer}px`;
        } else {
          document.body.style.height = '';
        }
        window.parent.postMessage({
          type: 'PCAT72_IFRAME_LAYOUT',
          height: heightWithBuffer,
          termsExpanded,
          termsOverflow
        }, '*');
      } catch (error) {
        // ignore cross-origin access errors
      }
    }
    function pcat72StartHeightSync() {
      pcat72SendHeightToParent();
      Kameleoon.API.Utils.addEventListener(window, 'resize', pcat72SendHeightToParent);
      window.setInterval(pcat72SendHeightToParent, pcat72Config.heightSyncInterval);
      if (window.ResizeObserver) {
        const resizeObserver = new ResizeObserver(() => {
          pcat72SendHeightToParent();
        });
        const contentEl = document.querySelector('.calculator-inner') || document.querySelector('.calculator') || document.querySelector('#main') || document.body;
        resizeObserver.observe(contentEl);
        const calculatorForm = document.querySelector('.calculator-form');
        if (calculatorForm) {
          resizeObserver.observe(calculatorForm);
        }
        const termsContent = document.querySelector('.pcat72-terms__content');
        if (termsContent) {
          resizeObserver.observe(termsContent);
        }
      }
      if (window.MutationObserver && document.body) {
        const mutationObserver = new MutationObserver(() => {
          pcat72SendHeightToParent();
        });
        mutationObserver.observe(document.body, {
          childList: true,
          subtree: true,
          attributes: true
        });
      }
    }
    function pcat72FinishInit() {
      pcat72IsLoading = false;
      pcat72SendHeightToParent();
      pcat72HideLoadingOverlay();
    }
    function pcat72Init() {
      document.body.classList.add('pcat72-iframe');
      pcat72TransformCalculatorUi();
      pcat72SetNativeDefaults();
      pcat72InitSliderFills();
      pcat72BindEvents();
      pcat72TriggerCalculation();
      pcat72StartHeightSync();
      pcat72FinishInit();
    }
    function pcat72Start() {
      if (!pcat72HasUrlParam()) {
        return;
      }
      if (document.readyState === 'loading') {
        Kameleoon.API.Utils.addEventListener(document, 'DOMContentLoaded', pcat72BindVariantChangeOverlay);
      } else {
        pcat72BindVariantChangeOverlay();
      }
      if (window.pcat72IframeStart) {
        return;
      }
      window.pcat72IframeStart = true;
      pcat72ShowLoadingOverlay();
      Kameleoon.API.Core.runWhenConditionTrue(() => document.querySelector('.calculator-form') && document.getElementById('interest'), () => {
        try {
          pcat72Init();
        } catch (error) {
          console.error('PCAT72 init failed', error);
        } finally {
          pcat72IsLoading = false;
          pcat72HideLoadingOverlay();
        }
      });
    }
    if (window.__kam406804Initialized) {
      return;
    }
    window.__kam406804Initialized = true;
    pcat72Start();
  })();
})();